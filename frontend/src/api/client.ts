import { ref } from 'vue'
import createClient from 'openapi-fetch'
import type { paths, components } from './generated/schema' // Generated by openapi-typescript

const token = ref<string | null>(null)
export const setApiAccessToken = (newToken: string | null) => {
  token.value = newToken
}

type ErrorResponse = components['schemas']['ErrorResponse']
export const makeErrorResponseHumanReadable = (error: ErrorResponse): string => {
  let message = error.message || 'An error occurred'

  // Check if error has any details
  if (error.errors && Array.isArray(error.errors) && error.errors.length > 0) {
    const details = error.errors.map((err) => err.message).join('; ')
    message += ` Details: ${details}`
    return message
  }

  return 'An unknown error occurred'
}

const client = createClient<paths>({
  baseUrl: import.meta.env.VITE_API_URL || 'http://localhost:8080',
  fetch: (input) => {
    const headers: Record<string, string> = {}
    if (token.value) {
      headers['Authorization'] = `Bearer ${token.value}`
    }
    const modifiedRequest = new Request(input, {
      headers: {
        ...Object.fromEntries(input.headers),
        ...headers,
      },
    })
    return fetch(modifiedRequest)
  },
})

export default client
